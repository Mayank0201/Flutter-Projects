///
/// Kept in its own file (like masyu_levels.dart and bridges_levels.dart) so
/// the data can be validated by tests. Every entry must satisfy: the solution
/// is a legal Sudoku for its box shape, every given matches the solution, and
/// the givens admit exactly one solution -- the win check compares against the
